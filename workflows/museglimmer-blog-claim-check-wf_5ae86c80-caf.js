export const meta = {
  name: 'museglimmer-blog-claim-check',
  description: 'Verify every number and claim in the Muse-Glimmer POC blog against the data files, logs and reports',
  phases: [{ title: 'Check', detail: '4 read-only checkers, one per group of sections' }],
}

const BASE = `You are checking the illustrated report of the Muse-Glimmer-30B strict train/rollout POC (RFC RL-Align/RL-Kernel#501) before
it is published. Repo worktree: /home/ubuntu/RL-Kernel/.claude/worktrees/swift-oak-hsv7 (branch feat/museglimmer-poc).
The page is reports/muse_glimmer_poc/blog/index.html, generated by reports/muse_glimmer_poc/blog/build_blog.py (+ svgkit.py, diagrams.py)
from reports/muse_glimmer_poc/data/*.json. Some prose/captions are hard-coded in build_blog.py; numbers in charts come from the JSON.
Supporting sources: rl_engine/models/muse_glimmer/**/REPORT_*.md, reports/muse_glimmer_poc/runs/*/ (GRPO run artifacts),
reports/muse_glimmer_poc/RFC_CHANGES.md, docs/contracts/muse-glimmer-30b-strict-contract.md, reports/muse_glimmer_poc/RESUME.md.
You are READ-ONLY: do not edit or commit anything; you may run python3 over the files (no GPUs needed).

For the sections assigned below: list every factual claim (numbers, counts, ratios, "byte-equal"/"0 differ" statements, versions,
causal explanations) in the rendered page text, chart titles, captions and card texts. For each, find its source and decide:
verified (source agrees), wrong (source disagrees: give the correct value and the source), unsupported (no source found), or
stale (true for an older run but superseded by newer data in the repo). Pay special attention to hard-coded text in build_blog.py
that may no longer match the regenerated data (wave B regenerated vLLM, Megatron, reference, ablation and attention data).
Also flag misleading framing (e.g. a comparison that is not apples-to-apples) and anything a skeptical reader would object to.
Return only problems (wrong / unsupported / stale / misleading) with the exact text, location (section id + build_blog.py line if
hard-coded), the evidence and the replacement text; plus a count of verified claims.`

const SCHEMA = {
  type: 'object',
  properties: {
    verified_count: { type: 'integer' },
    problems: { type: 'array', items: { type: 'object', properties: {
      kind: { type: 'string', enum: ['wrong', 'unsupported', 'stale', 'misleading'] },
      section: { type: 'string' }, text: { type: 'string' }, where: { type: 'string' },
      evidence: { type: 'string' }, replacement: { type: 'string' } },
      required: ['kind', 'section', 'text', 'evidence', 'replacement'] } },
  },
  required: ['verified_count', 'problems'],
}

const GROUPS = [
  { key: 'top', sections: 'the masthead/hero bit strip, #verdict, #why, #scope (incl. the row status cards), #model (incl. the "RFC 里需要改的几个数" cards), #contract' },
  { key: 'kernels_runtimes', sections: '#ws1, #chain, #multi, #runtimes' },
  { key: 'results', sections: '#xrt, #e2e (note: a fifth strict/strict run in the RFC layout rollout TP2 + train TP4 may still be running; judge the four completed modes), #ablation, #profile' },
  { key: 'process_rfc', sections: '#timeline, #rfc (the 20 findings cards and the audit list), #left; and check reports/muse_glimmer_poc/RFC_CHANGES.md part 1 against the evidence it cites and against docs/contracts (e.g. whether O5/O7 already contain what a finding asks for)' },
]

const results = await parallel(GROUPS.map((g) => () =>
  agent(`${BASE}\n\nYour sections: ${g.sections}.`, { label: `check:${g.key}`, phase: 'Check', schema: SCHEMA, effort: 'high' })
    .then((r) => ({ group: g.key, ...(r || { verified_count: 0, problems: [] }) }))))
return results

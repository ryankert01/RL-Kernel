"""Write reports/muse_glimmer_poc/RFC_CHANGES.md: the paste-ready list of RFC #501 edits.

Part 1 comes from data/rfc_findings.json (changes that surfaced while implementing),
part 2 from data/rfc_audit.json (the verified line-by-line audit of the RFC text).
"""

from __future__ import annotations

import json
from pathlib import Path

POC = Path(__file__).resolve().parents[1]


def main() -> None:
    findings = json.loads((POC / "data/rfc_findings.json").read_text())["items"]
    audit = json.loads((POC / "data/rfc_audit.json").read_text())["items"]
    out = [
        "# RFC #501 — proposed changes from the Muse-Glimmer-30B POC",
        "",
        "Generated by `reports/muse_glimmer_poc/tools/make_rfc_changes.py` from `data/rfc_findings.json` and",
        "`data/rfc_audit.json`. Part 1 lists what only surfaced while implementing; part 2 is the line-by-line",
        f"audit of the RFC text ({len(audit)} edits, each independently re-verified).",
        "",
        "## Part 1 — findings from the implementation",
        "",
    ]
    for f in findings:
        out += [f"### {f['id']}. {f['title_en']}", "", f"*Where:* {f['area']}", "", f["body_en"], "", f"*Evidence:* {f['evidence']}", ""]
    out += ["## Part 2 — line-by-line audit of the RFC text", "", f"Evidence paths: {json.loads((POC / 'data/rfc_audit.json').read_text()).get('evidence_legend', '')}", "", json.loads((POC / 'data/rfc_audit.json').read_text()).get('note_semantics_source', ''), ""]
    section = None
    for it in audit:
        if it["section"] != section:
            section = it["section"]
            out += [f"### {section}", ""]
        proposed = it.get("corrected") or it.get("proposed", "")
        out += [
            f"#### {it['id']} ({it['kind'].replace('_', ' ')}; verdict {it['verdict'].replace('_', ' ')})",
            "",
            f"> {it.get('rfc', '')}",
            "",
            f"**Problem.** {it.get('problem', '')}",
            "",
            f"**Proposed text.** {proposed}",
            "",
            f"*Evidence:* {it.get('evidence', '')}",
            "",
        ]
    (POC / "RFC_CHANGES.md").write_text("\n".join(out))
    print(f"wrote {POC / 'RFC_CHANGES.md'}: {len(findings)} findings + {len(audit)} audit edits")


if __name__ == "__main__":
    main()
